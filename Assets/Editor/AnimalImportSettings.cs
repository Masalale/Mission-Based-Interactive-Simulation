using UnityEditor;

namespace Safari.EditorTools
{
    /// <summary>
    /// Import settings for every model under Assets/Models/Animals (the Big 5 and the
    /// jaguar used as the leopard). This is the only code that owns those files'
    /// import settings.
    ///
    /// bakeAxisConversion stays OFF. The Blender exports already carry the axis
    /// conversion in their vertices (bake_space_transform), so Unity baking it again
    /// applies the conversion twice and the animal faces -Z. Measured in Unity
    /// 6000.3 on SM_Lion: with the flag off the import is scale 1, rotation 0, facing
    /// +Z; with it on, the same readings hold but the animal faces -Z.
    ///
    /// Everything else is what the build relies on: no animation, cameras or lights
    /// (the animals are rigid), meshes not readable from script, and no mesh LODs
    /// generated by Unity on top of the authored meshes.
    /// </summary>
    public sealed class AnimalImportSettings : AssetPostprocessor
    {
        private const string AnimalsRoot = "Assets/Models/Animals/";

        private void OnPreprocessModel()
        {
            if (!assetPath.StartsWith(AnimalsRoot))
                return;

            var importer = (ModelImporter)assetImporter;

            importer.globalScale = 1f;
            importer.bakeAxisConversion = false;
            importer.meshCompression = ModelImporterMeshCompression.Off;

            importer.importAnimation = false;
            importer.importCameras = false;
            importer.importLights = false;
            importer.animationType = ModelImporterAnimationType.None;

            importer.isReadable = false;
            importer.generateMeshLods = false;
        }
    }
}
